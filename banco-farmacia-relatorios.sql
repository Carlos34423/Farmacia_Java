-- =====================================================================
-- Farmácia - esquema reconstruído a partir dos DAOs + tabelas novas p/ relatórios
-- Banco: MySQL 8 | Execute inteiro (HeidiSQL / Workbench). É idempotente.
--  * Tabelas que o projeto já usa: CREATE TABLE IF NOT EXISTS (não altera as existentes)
--  * Novas: venda, itemVenda (histórico de vendas, necessário para os relatórios)
--  * Novas colunas em medicamento: precoCusto, dataValidade, estoqueMinimo
-- =====================================================================
CREATE DATABASE IF NOT EXISTS `farmacia` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `farmacia`;

CREATE TABLE IF NOT EXISTS cidade (
  codigoCidade INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  uf CHAR(2) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS cargo (
  codigoCargo INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  salarioBase DOUBLE NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS convenio (
  codigoConvenio INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  percentualDesconto DOUBLE NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CategoriaMedicamento (
  codigoCategoriaMedicamento INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  descricao VARCHAR(255)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS fabricante (
  cnpj VARCHAR(20) NOT NULL PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  telefone VARCHAR(20),
  email VARCHAR(100)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS formaPagamento (
  codigoFormaPagamento INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  descricao VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS fornecedor (
  codigoFornecedor INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  razaoSocial VARCHAR(150) NOT NULL,
  nomeFantasia VARCHAR(150),
  cnpj VARCHAR(20),
  telefone VARCHAR(20),
  email VARCHAR(100),
  codigoCidade INT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS funcionario (
  codigoFuncionario INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  cpf VARCHAR(14),
  telefone VARCHAR(20),
  email VARCHAR(100),
  codigoCargo INT,
  codigoCidade INT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS cliente (
  codigoCliente INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  cpf VARCHAR(14),
  telefone VARCHAR(20),
  email VARCHAR(100),
  codigoCidade INT,
  codigoConvenio INT,
  carteira FLOAT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS medicamento (
  codigoMedicamento INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(150) NOT NULL,
  descricao VARCHAR(255),
  precoVenda DOUBLE NOT NULL,
  quantidadeEstoque INT NOT NULL DEFAULT 0,
  codigoCategoriaMedicamento INT,
  cnpjFabricante VARCHAR(20),
  codigoFornecedor INT
) ENGINE=InnoDB;

-- Colunas novas em medicamento (só adiciona se ainda não existirem)
SET @s := IF((SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='medicamento' AND COLUMN_NAME='precoCusto')=0,
  'ALTER TABLE medicamento ADD COLUMN precoCusto DECIMAL(10,2) NULL', 'DO 0');
PREPARE st FROM @s; EXECUTE st; DEALLOCATE PREPARE st;
SET @s := IF((SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='medicamento' AND COLUMN_NAME='dataValidade')=0,
  'ALTER TABLE medicamento ADD COLUMN dataValidade DATE NULL', 'DO 0');
PREPARE st FROM @s; EXECUTE st; DEALLOCATE PREPARE st;
SET @s := IF((SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='medicamento' AND COLUMN_NAME='estoqueMinimo')=0,
  'ALTER TABLE medicamento ADD COLUMN estoqueMinimo INT NOT NULL DEFAULT 10', 'DO 0');
PREPARE st FROM @s; EXECUTE st; DEALLOCATE PREPARE st;

-- Histórico de vendas (cabeçalho + itens)
CREATE TABLE IF NOT EXISTS venda (
  codigoVenda INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  dataVenda DATETIME NOT NULL,
  codigoCliente INT NOT NULL,
  codigoFuncionario INT NULL,
  codigoFormaPagamento INT NULL,
  percentualDesconto DECIMAL(5,2) NOT NULL DEFAULT 0,
  valorTotal DECIMAL(10,2) NOT NULL,
  INDEX idx_venda_data (dataVenda),
  INDEX idx_venda_cliente (codigoCliente),
  INDEX idx_venda_func (codigoFuncionario)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS itemVenda (
  codigoItemVenda INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigoVenda INT NOT NULL,
  codigoMedicamento INT NOT NULL,
  quantidade INT NOT NULL,
  precoUnitario DECIMAL(10,2) NOT NULL,
  INDEX idx_item_venda (codigoVenda),
  INDEX idx_item_med (codigoMedicamento),
  CONSTRAINT fk_item_venda FOREIGN KEY (codigoVenda) REFERENCES venda(codigoVenda) ON DELETE CASCADE
) ENGINE=InnoDB;

